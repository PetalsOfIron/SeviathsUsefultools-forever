"""Bakes Data/QuestPrereqs.lua from tools/crawl/quest_prereqs.txt (made by crawl_quest_prereqs.py): SFP.QuestPrereq[quest] = the quest before it in its chain."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
rows = {}
for l in open(os.path.join(HERE, "crawl", "quest_prereqs.txt"), encoding="utf8").read().splitlines():
    a, _, b = l.partition("|")
    if a.isdigit() and b.isdigit(): rows[int(a)] = int(b)
out = ["-- SeviathsUsefulTools - the quest before a quest in its chain (generated by tools/bake_quest_prereqs.py from Wowhead)", "local _, SFP = ...", "SFP.QuestPrereq = {"]
out += ["[%d]=%d," % (k, rows[k]) for k in sorted(rows)]
out.append("}\n")
open(os.path.join(os.path.dirname(HERE), "Data", "QuestPrereqs.lua"), "w", encoding="utf8", newline="\n").write("\n".join(out))
print(len(rows), "chain links")
