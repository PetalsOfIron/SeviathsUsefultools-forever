"""Adds the S tier hunter pets (the families Icy Veins recommends for WoW Forever hunters) to Data/Rares.lua as hunter spots on the map.

For each family page of Wowhead Classic (/classic/pet=ID/name) the tameable monsters are listed with their zone and level; per zone the three lowest
level ones are kept and their places are read from their own pages (g_mapperData).
Run: python tools/bake_hunter_pets_forever.py   (replaces the block between the markers in Data/Rares.lua)
"""
import json
import os
import re
import sys
import time
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)
AREA_MAPS = {int(k): v for k, v in json.load(open(os.path.join(HERE, "area_maps.json"))).items()}

# family id, name, tier, what it gives (Icy Veins, "Looking for the perfect hunter pet", and the family abilities)
FAMILIES = [
    (1, "wolf", "Wolf", "S", "Furious Howl: more melee attack power for the party within 15 yards. The group pet."),
    (2, "cat", "Cat", "S", "Prowl, Bite, Claw, Dash: the damage pet for solo leveling."),
    (4, "bear", "Bear", "S", "Swipe hits several enemies; sturdy, eats nearly everything. The tank pet."),
    (5, "boar", "Boar", "S", "Charge immobilizes the target and raises its next attack. A solid first tame."),
    (7, "carrion-bird", "Carrion Bird", "S", "Demoralizing Screech lowers the attack power of nearby enemies."),
]
PER_ZONE = 3
START = "-- hunter pets (S tier): generated by tools/bake_hunter_pets_forever.py"
END = "-- end of the hunter pets"


def fetch(path):
    # Wowhead answers 403 when asked too fast: wait and ask again (30 s, 60 s, 120 s ...)
    for attempt in range(6):
        req = urllib.request.Request("https://www.wowhead.com" + path, headers={"User-Agent": "Mozilla/5.0"})
        try:
            return urllib.request.urlopen(req, timeout=60).read().decode("utf-8", "replace")
        except urllib.error.HTTPError as e:
            if e.code not in (403, 429) or attempt == 5:
                raise
            print("  waiting %d s (%d)" % (30 * 2 ** attempt, e.code), file=sys.stderr)
            time.sleep(30 * 2 ** attempt)


def tameable(html):
    i = html.find("id: 'tameable'")
    j = html.find("data: [", i)
    s = j + len("data: ")
    depth = 0
    end = s
    for q in range(s, len(html)):
        c = html[q]
        if c == "[":
            depth += 1
        elif c == "]":
            depth -= 1
            if depth == 0:
                end = q + 1
                break
    return json.loads(re.sub(r"([,{])([A-Za-z_][A-Za-z0-9_]*):", r'\1"\2":', html[s:end]))


def mapper(html):
    i = html.find("g_mapperData = ")
    if i < 0:
        return {}
    j = html.find(";\n", i)
    d = json.loads(html[i + 15:j])
    return d if isinstance(d, dict) else {}


def pick(coords, n=5):
    if len(coords) <= n:
        return coords
    return [coords[int(k * (len(coords) - 1) / (n - 1))] for k in range(n)]


lines = [START]
total = 0
for fid, slug, name, tier, note in FAMILIES:
    rows = tameable(fetch("/classic/pet=%d/%s" % (fid, slug)))
    byzone = {}
    for r in rows:
        if not r.get("location"):
            continue
        byzone.setdefault(tuple(r["location"]), []).append(r)
    kept = []
    for zone, rs in byzone.items():
        rs.sort(key=lambda x: (x.get("minlevel", 0), x["id"]))
        kept.extend(rs[:PER_ZONE])
    print(name, len(rows), "tameable,", len(kept), "kept", file=sys.stderr)
    for r in kept:
        time.sleep(1.0)
        try:
            data = mapper(fetch("/classic/npc=%d" % r["id"]))
        except Exception as e:
            print("  failed", r["id"], e, file=sys.stderr)
            continue
        byMap = {}
        for area, arr in data.items():
            m = AREA_MAPS.get(int(area))
            if not m:
                continue
            for part in arr:
                byMap.setdefault(m, []).extend(part.get("coords", []))
        lv = r.get("minlevel", 0)
        lv2 = r.get("maxlevel", lv)
        for m, coords in byMap.items():
            if not coords:
                continue
            pts = ";".join("%s,%s" % (c[0], c[1]) for c in pick(coords))
            text = "%s (%s tier), level %s: %s" % (name, tier, lv if lv == lv2 else "%s-%s" % (lv, lv2), note)
            lines.append('addRare(%d, %d, "%s", "%s", "%s", "tame")' % (m, r["id"], r["name"].replace('"', "'"), text.replace('"', "'"), pts))
            total += 1
lines.append(END)

path = os.path.join(ADDON, "Data", "Rares.lua")
raw = open(path, "rb").read().decode("utf8")
nl = "\r\n" if "\r\n" in raw else "\n"
t = raw.replace("\r\n", "\n")
if START in t:
    t = t[:t.index(START)].rstrip("\n") + "\n" + t[t.index(END) + len(END):].lstrip("\n")
# the addRare helper takes the hunter kind as a sixth argument
t = t.replace("local function addRare(map, npc, name, note, pts)", "local function addRare(map, npc, name, note, pts, hunter)")
t = t.replace("block[#block + 1] = { npc = npc, name = name, items = {}, note = note, pts = pts }",
              "block[#block + 1] = { npc = npc, name = name, items = {}, note = note, pts = pts, hunter = hunter }")
t = t.rstrip("\n") + "\n\n" + "\n".join(lines) + "\n"
open(path, "wb").write(t.replace("\n", nl).encode("utf8"))
print("added", total, "hunter spots")
