"""Reads the quests of each holiday event from Wowhead Classic (/classic/event=ID) and writes Data/EventQuests.lua:
SFP.EventQuests[questID] = "Event name" (the name as the game's calendar shows it). Run: python tools/crawl_event_quests.py"""
import json, os, re, time, urllib.error, urllib.request
HERE = os.path.dirname(os.path.abspath(__file__))
EVENTS = {479: "Darkmoon Faire", 141: "Feast of Winter Veil", 324: "Hallow's End", 327: "Lunar Festival", 423: "Love is in the Air", 341: "Midsummer",
          321: "Harvest Festival", 372: "Brewfest", 181: "Noblegarden", 201: "Children's Week", 301: "Stranglethorn Fishing Extravaganza", 409: "Day of the Dead"}
def fetch(path):
    for a in range(8):
        try:
            time.sleep(1.1)
            return urllib.request.urlopen(urllib.request.Request("https://www.wowhead.com" + path, headers={"User-Agent": "Mozilla/5.0"}), timeout=60).read().decode("utf-8", "replace")
        except urllib.error.HTTPError as e:
            if e.code not in (403, 429, 503) or a == 7: raise
            time.sleep(min(30 * 2 ** a, 600))
def listview(html, lv):
    i = html.find("id: '%s'" % lv)
    if i < 0: return []
    s = html.find("[", html.find("data:", i)); d = 0
    for q in range(s, len(html)):
        d += (html[q] == "[") - (html[q] == "]")
        if d == 0: break
    try: return json.loads(re.sub(r"([,{])([A-Za-z_][A-Za-z0-9_]*):", r'\1"\2":', html[s:q + 1]))
    except Exception: return []
rows = {}
for eid, name in EVENTS.items():
    try:
        for q in listview(fetch("/classic/event=%d" % eid), "quests"):
            if "id" in q: rows[q["id"]] = name
        print(name, sum(1 for v in rows.values() if v == name), flush=True)
    except Exception as e:
        print(name, "failed", e, flush=True)
out = ["-- SeviathsUsefulTools - the quests of the holiday events (generated by tools/crawl_event_quests.py from Wowhead)", "local _, SFP = ...", "SFP.EventQuests = {"]
out += ['[%d]="%s",' % (k, rows[k].replace('"', "'")) for k in sorted(rows)]
out.append("}\n")
open(os.path.join(os.path.dirname(HERE), "Data", "EventQuests.lua"), "w", encoding="utf8", newline="\n").write("\n".join(out))
print(len(rows), "event quests")
