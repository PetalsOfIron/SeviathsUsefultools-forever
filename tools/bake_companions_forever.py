"""Bakes Data/CompanionItems.lua: the mount items (item class 15, subclass 5) and the companion pet items (15, 2) of the Classic list, with where they come from.

Source: tools/items_sources.txt  id|name|quality|source types|sourcemore|item class|subclass|slot|level|required level|list
  source types: 1 crafted, 2 drop, 3 PvP, 4 quest, 5 vendor ...; sourcemore: "type:id:zone:name:difficulty:boss flag" parts joined by ";"
Run: python tools/bake_companions_forever.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)
SKIP = re.compile(r"(?i)deprecated|deptecated|\[ph\]|zzold|\btest\b|unused|\bnot used\b")
KIND = {"1": "Crafted", "2": "Drop", "3": "PvP", "4": "Quest", "5": "Vendor", "6": "Trainer"}


def lua(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


mounts, pets = [], []
for line in open(os.path.join(HERE, "items_sources.txt"), encoding="utf8").read().splitlines():
    p = line.split("|")
    if len(p) < 11 or not p[0].isdigit() or p[5] != "15" or p[6] not in ("5", "2") or SKIP.search(p[1]):
        continue
    types = [KIND.get(t, "") for t in p[3].split(",") if t]
    where = []
    npc = 0
    for part in p[4].split(";"):
        f = part.split(":")
        if len(f) >= 4 and f[0] == "1" and f[1].isdigit() and f[3]:
            where.append(f[3])
            npc = npc or int(f[1])
    text = ""
    if where:
        text = ("Vendor: " if "Vendor" in types else "Drop: ") + ", ".join(where[:2])
    elif types:
        text = ", ".join(t for t in types if t)
    row = "[%s]={%s,%s,%d}," % (p[0], lua(p[1]), lua(text), npc)
    (mounts if p[6] == "5" else pets).append(row)

out = ["-- SeviathsUsefulTools - the mounts and companion pets of Classic with their source (generated by tools/bake_companions_forever.py)",
       "-- SFP.MountItems[itemID] = { name, source text, npc ID of the vendor or monster (0 = unknown) }; the same for SFP.PetItems", "",
       "local _, SFP = ...", "", "SFP.MountItems = {"] + mounts + ["}", "", "SFP.PetItems = {"] + pets + ["}", ""]
open(os.path.join(ADDON, "Data", "CompanionItems.lua"), "w", encoding="utf8", newline="\n").write("\n".join(out))
print(len(mounts), "mount items,", len(pets), "companion pet items")
