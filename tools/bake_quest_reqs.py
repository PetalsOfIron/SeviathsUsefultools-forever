"""Bakes Data/QuestReqs.lua from tools/crawl/quest_reqs.txt (made by crawl_quest_reqs.py):
SFP.QuestReq[quest] = { classMask, raceMask } for quests only some classes or races can take, SFP.QuestSoD[quest] = true for Season of Discovery quests,
SFP.QuestNeeds[quest] = { quests that must be turned in first }."""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
rows = {}
for l in open(os.path.join(HERE, "crawl", "quest_reqs.txt"), encoding="utf8").read().splitlines():
    p = l.split("|")
    if len(p) >= 4 and p[0].isdigit():
        rows[int(p[0])] = p            # the last line of a quest is the newest
req, sod, needs, rep = [], [], [], []
for q in sorted(rows):
    p = rows[q]
    c, r, s = int(p[1]), int(p[2]), int(p[3])
    pre = [x for x in (p[4].split(",") if len(p) > 4 else []) if x.isdigit()]
    if c or r: req.append("[%d]={%d,%d}," % (q, c, r))
    if s: sod.append("[%d]=true," % q)
    if len(p) > 5 and p[5] == "1": rep.append("[%d]=true," % q)
    if pre: needs.append("[%d]={%s}," % (q, ",".join(pre)))
out = ["-- SeviathsUsefulTools - what a quest needs: class / race, Season of Discovery quests, quests to turn in first (generated by tools/bake_quest_reqs.py from Wowhead)",
       "local _, SFP = ...", "SFP.QuestReq = {"] + req + ["}", "SFP.QuestSoD = {"] + sod + ["}", "SFP.QuestNeeds = {"] + needs + ["}", ""]
open(os.path.join(os.path.dirname(HERE), "Data", "QuestReqs.lua"), "w", encoding="utf8", newline="\n").write("\n".join(out))
print(len(rows), "quests,", len(req), "with a class/race,", len(sod), "Season of Discovery,", len(needs), "with prerequisites")
