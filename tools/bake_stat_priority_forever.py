"""Bakes Data/StatPriority.lua for WoW Forever from tools/stat_priority_forever.txt (the stat priority pages of Icy Veins' WoW Forever guides).
Line: CLASS:Spec : Stat > Stat > ... [ || second list ]. The talent advisor ranks a spec's talents by these stats (the first stat counts most).
Run: python tools/bake_stat_priority_forever.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)
rows = []
for line in open(os.path.join(HERE, "stat_priority_forever.txt"), encoding="utf8").read().splitlines():
    if " : " not in line:
        continue
    key, lists = line.split(" : ", 1)
    parts = [[s.strip() for s in lst.split(">") if s.strip()] for lst in lists.split("||")]
    rows.append('SP["%s"] = { %s }' % (key.strip(), ", ".join("{ " + ", ".join('"%s"' % s for s in p) + " }" for p in parts)))
out = ["-- SeviathsUsefulTools - stat priority of every specialization for WoW Forever (generated by tools/bake_stat_priority_forever.py from Icy Veins)",
       "-- SFP.StatPriority[\"CLASS:Spec\"] = { { first list of stats, best first }, { second list (a spec that plays two roles) } }",
       "", "local _, SFP = ...", "", "local SP = {}", "SFP.StatPriority = SP", ""] + rows
open(os.path.join(ADDON, "Data", "StatPriority.lua"), "w", encoding="utf8", newline="\n").write("\n".join(out) + "\n")
print(len(rows), "specializations")
