"""Bakes Data/RecipeData.lua for WoW Forever from Wowhead Classic's profession pages (name, crafted item, reagents).

Same row format as the retail data: { spellID, profession, recipe name, crafted item ID (0 = none), { {reagent item ID, amount}, ... } }
Run: python tools/bake_recipes_forever.py
"""
import json
import os
import re
import sys
import time
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "Data", "RecipeData.lua")

PAGES = ["/classic/spells/professions/alchemy", "/classic/spells/professions/blacksmithing", "/classic/spells/secondary-skills/cooking",
         "/classic/spells/professions/enchanting", "/classic/spells/professions/engineering", "/classic/spells/secondary-skills/first-aid",
         "/classic/spells/professions/leatherworking", "/classic/spells/professions/tailoring", "/classic/spells/professions/mining"]
SKILL = {171: "Alchemy", 164: "Blacksmithing", 185: "Cooking", 333: "Enchanting", 202: "Engineering", 129: "First Aid", 165: "Leatherworking",
         197: "Tailoring", 186: "Mining"}


def fetch(path):
    req = urllib.request.Request("https://www.wowhead.com" + path, headers={"User-Agent": "Mozilla/5.0"})
    return urllib.request.urlopen(req, timeout=60).read().decode("utf-8", "replace")


def rows_of(html):
    i = html.find("var listviewspells = [")
    if i < 0:
        return []
    s = i + len("var listviewspells = ")
    depth = 0
    end = s
    for q in range(s, len(html)):
        c = html[q]
        if c == "[":
            depth += 1
        elif c == "]":
            depth -= 1
            if depth == 0:
                end = q + 1
                break
    body = re.sub(r"([,{])(quality|popularity):", r'\1"\2":', html[s:end])
    return json.loads(body)


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


rows = {}
for page in PAGES:
    try:
        data = rows_of(fetch(page))
    except Exception as e:
        print("failed", page, e, file=sys.stderr)
        continue
    n = 0
    for x in data:
        prof = SKILL.get((x.get("skill") or [0])[0])
        reag = x.get("reagents") or []
        if not prof or not reag or not x.get("name"):
            continue
        creates = (x.get("creates") or [0])[0]
        rows[x["id"]] = (prof, x["name"], creates, reag)
        n += 1
    print(page.split("/")[-1], n, "recipes")
    time.sleep(2)

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- SeviathsUsefulTools - crafting recipes of WoW Forever (generated by tools/bake_recipes_forever.py from Wowhead Classic)\n")
    f.write("-- Row: { spellID, profession, recipe name, crafted item ID (0 = none), { {reagent item ID, amount}, ... } }\n\n")
    f.write("local _, SFP = ...\n\nSFP.RecipeData = {\n")
    for sid in sorted(rows, key=lambda k: (rows[k][0], rows[k][1], k)):
        prof, name, out, reag = rows[sid]
        f.write("{%d,%s,%s,%d,{%s}},\n" % (sid, lua_str(prof), lua_str(name), out, ",".join("{%d,%d}" % (r[0], r[1]) for r in reag)))
    f.write("}\n")
print("wrote", len(rows), "recipes")
