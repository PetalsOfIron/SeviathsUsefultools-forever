"""Finds where each Classic mount comes from (the vendor or monster, with its place) and writes Data/MountPlaces.lua:
SFP.MountPlaces[itemID] = { npcID, "name", uiMapID, x, y }   (x and y as 0-1 of the zone map)

For each mount item of Data/CompanionItems.lua the Wowhead Classic item page lists who sells or drops it; the first one found is read for its place.
Slow and polite (one page a second, waits after a 403); stop it and run it again to continue. Run: python tools/bake_mount_places.py
"""
import json
import os
import re
import time
import urllib.error
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)
AREA = {int(k): v for k, v in json.load(open(os.path.join(HERE, "area_maps.json"))).items()}   # Wowhead zone number -> uiMapID
CACHE = os.path.join(HERE, "crawl", "mount_places.json")


def fetch(path):
    for attempt in range(8):
        req = urllib.request.Request("https://www.wowhead.com" + path, headers={"User-Agent": "Mozilla/5.0"})
        try:
            time.sleep(1.1)
            return urllib.request.urlopen(req, timeout=60).read().decode("utf-8", "replace")
        except urllib.error.HTTPError as e:
            if e.code not in (403, 429, 503) or attempt == 7:
                raise
            time.sleep(min(30 * 2 ** attempt, 600))


def listview(html, lv_id):
    i = html.find("id: '%s'" % lv_id)
    if i < 0:
        return []
    s = html.find("[", html.find("data:", i))
    depth = 0
    for q in range(s, len(html)):
        depth += (html[q] == "[") - (html[q] == "]")
        if depth == 0:
            break
    try:
        return json.loads(re.sub(r"([,{])([A-Za-z_][A-Za-z0-9_]*):", r'\1"\2":', html[s:q + 1]))
    except Exception:
        return []


def place_of(npc):
    html = fetch("/classic/npc=%d" % npc)
    i = html.find("g_mapperData = ")
    if i < 0:
        return None
    try:
        data = json.loads(html[i + 15:html.find(";\n", i)])
    except Exception:
        return None
    for area, arr in (data.items() if isinstance(data, dict) else []):
        for part in arr:
            for c in part.get("coords", []):
                m = AREA.get(int(area))
                if m:
                    return m, round(c[0] / 100, 4), round(c[1] / 100, 4)
    return None


text = open(os.path.join(ADDON, "Data", "CompanionItems.lua"), encoding="utf8").read()
mounts = re.findall(r'^\[(\d+)\]=\{"(.*?)"', text.split("SFP.MountItems = {")[1].split("SFP.PetItems = {")[0], re.M)
found = json.load(open(CACHE)) if os.path.exists(CACHE) else {}
for item, name in mounts:
    if item in found:
        continue
    try:
        html = fetch("/classic/item=" + item)
        who = []
        for lv in ("sold-by", "dropped-by", "pick-pocketed-from"):
            who += [r for r in listview(html, lv) if "id" in r]
        res = None
        for npc in who[:3]:
            p = place_of(npc["id"])
            if p:
                res = [npc["id"], npc.get("name", ""), p[0], p[1], p[2]]
                break
        found[item] = res
    except Exception as e:
        print("item", item, "failed", e, flush=True)
        continue
    json.dump(found, open(CACHE, "w"))
    print(item, name, found[item], flush=True)

out = ["-- SeviathsUsefulTools - where the mounts of Classic come from (generated by tools/bake_mount_places.py)",
       "local _, SFP = ...", "SFP.MountPlaces = {"]
for item, r in sorted(found.items(), key=lambda kv: int(kv[0])):
    if r:
        out.append('[%s]={%d,"%s",%d,%s,%s},' % (item, r[0], r[1].replace('"', "'"), r[2], r[3], r[4]))
out.append("}\n")
open(os.path.join(ADDON, "Data", "MountPlaces.lua"), "w", encoding="utf8", newline="\n").write("\n".join(out))
print("written", sum(1 for r in found.values() if r), "places")
