"""Bakes Data/TalentBuilds.lua for WoW Forever from tools/talent_builds_forever.txt (read from Icy Veins' WoW Forever pages with their talent calculator).

Line: page | build name | required level | Tree=Talent:rank,Talent:rank / Tree=... / Tree=...
Output row (the same shape as the retail rows): { build name, content, "forever:Tree=Talent:rank,...;Tree=...", source "I" (Icy Veins), date }
The string starts with "forever:" so the advisor knows it lists talent names and ranks per tree (not a Blizzard import string).
Run: python tools/bake_talent_builds_forever.py
"""
import os
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)

CLASS = {"warrior": "WARRIOR", "paladin": "PALADIN", "hunter": "HUNTER", "rogue": "ROGUE", "priest": "PRIEST", "shaman": "SHAMAN",
         "mage": "MAGE", "warlock": "WARLOCK", "druid": "DRUID"}
# the page names the specialization; the game names it by its talent tree
SPEC = {"beast-mastery": "Beast Mastery", "marksmanship": "Marksmanship", "survival": "Survival", "shadow": "Shadow Magic",
        "elemental": "Elemental Combat", "enhancement": "Enhancement", "restoration": "Restoration", "feral": "Feral Combat"}


def spec_of(page):
    words = page.split("-")
    cls = next(w for w in words if w in CLASS)
    head = "-".join(words[:words.index(cls)])
    if head in SPEC:
        return CLASS[cls], SPEC[head]
    return CLASS[cls], head.replace("-", " ").title()


def content_of(name):
    n = name.lower()
    if "pvp" in n or "leveling" in n or "world" in n and "solo" not in n:
        return "other"
    if "dungeon" in n or "solo" in n:
        return "dungeon"
    return "raid"


def esc(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


builds = {}
for line in open(os.path.join(HERE, "talent_builds_forever.txt"), encoding="utf8").read().splitlines():
    p = [x.strip() for x in line.split(" | ")]
    if len(p) < 4:
        continue
    key = "%s:%s" % spec_of(p[0])
    trees = []
    for part in p[3].split(" / "):
        tree, _, talents = part.partition("=")
        if talents:
            trees.append("%s=%s" % (tree.strip(), talents.strip()))
    builds.setdefault(key, []).append((p[1], content_of(p[1]), "forever:" + ";".join(trees)))

today = time.strftime("%Y-%m-%d")
out = ["-- SeviathsUsefulTools - recommended talent builds of every specialization for WoW Forever (generated by tools/bake_talent_builds_forever.py)",
       "-- Read from Icy Veins' WoW Forever talent pages. Row: { build name, content (raid, dungeon, other), \"forever:Tree=Talent:rank,...;Tree=...\", source (I Icy Veins), date }.",
       "-- The string lists the talents of the build by name and rank in each tree (Forever has its own talent trees; there is no Blizzard import string).",
       "",
       "local _, SFP = ...",
       "",
       "local B = {}",
       "SFP.TalentBuilds = B",
       'SFP.TalentBuildsPatch = "Forever 1.60"',
       'SFP.TalentBuildsBaked = "%s"' % today,
       ""]
for key in sorted(builds):
    rows = ",\n    ".join("{%s,%s,%s,\"I\",\"\"}" % (esc(n), esc(c), esc(s)) for n, c, s in builds[key])
    out.append('B[%s] = { updated = "?", patch = "Forever 1.60",\n    %s }' % (esc(key), rows))
open(os.path.join(ADDON, "Data", "TalentBuilds.lua"), "w", encoding="utf8", newline="\n").write("\n".join(out) + "\n")
print("%d specializations, %d builds" % (len(builds), sum(len(v) for v in builds.values())))
for k in sorted(builds):
    print(" ", k, [(n, c) for n, c, _ in builds[k]])
