"""Bakes Data/ServicePins.lua from the Questie data (see bake_questie.py): the profession trainers, bankers and auctioneers of every zone,
SFP.ServicePins[uiMapId] = { { label, kind, x, y, npcName, faction }, ... }   (x, y are fractions of the map, kind = "prof" / "bank" / "auction")

Run:  python tools/bake_services.py        (needs: pip install cbor2; the same Questie data as bake_questie.py)
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bake_questie as b   # noqa: E402

PROFMAP = [("alchem", "Alchemy"), ("blacksmith", "Blacksmithing"), ("armor crafter", "Blacksmithing"), ("weapon crafter", "Blacksmithing"), ("enchant", "Enchanting"),
           ("engineer", "Engineering"), ("leatherwork", "Leatherworking"), ("tailor", "Tailoring"), ("herbal", "Herbalism"), ("mining", "Mining"), ("miner", "Mining"),
           ("skinn", "Skinning"), ("cook", "Cooking"), ("butcher", "Cooking"), ("fisher", "Fishing"), ("first aid", "First Aid"), ("physician", "First Aid"),
           ("medic", "First Aid"), ("surgeon", "First Aid"), ("jewelcraft", "Jewelcrafting"), ("inscription", "Inscription"), ("archaeolog", "Archaeology")]
RANKS = ("Apprentice", "Junior", "Journeyman", "Expert", "Artisan", "Superior", "Master", "Grand Master")


def profession(sub):
    low = sub.lower()
    if "pet" in low or "riding" in low:
        return None
    for key, prof in PROFMAP:
        if key in low:
            rank = next((r for r in RANKS if low.startswith(r.lower())), None)
            return "%s Trainer%s" % (prof, (" (%s)" % rank) if rank else "")
    return None


def main():
    kv = b.read_store()
    amap, sub = b.area_to_map()
    ids = sorted({int(m.group(1)) for k in kv for m in [re.match(r"X-Npc-(\d+)-S$", k)] if m})
    out = {}
    n = 0
    for i in ids:
        r = b.row(kv, "Npc", i)
        if not r:
            continue
        sn = b.text(r.get(14)) or ""
        name = b.text(r.get(1))
        if not isinstance(sn, str) or not isinstance(name, str):
            continue
        low = sn.lower()
        kind = None
        label = sn
        if low in ("banker",):
            kind, label = "bank", "Banker"
        elif low.startswith("auctioneer") or (isinstance(r.get(15), int) and r.get(15) & 4096 and name.startswith("Auctioneer")):
            kind, label = "auction", "Auction house"
        elif isinstance(r.get(15), int) and r.get(15) & 16 and profession(sn):
            kind, label = "prof", profession(sn)
        if not kind:
            continue
        spawns = b.table_field(kv, "Npc", i, 7)
        if not isinstance(spawns, dict):
            continue
        faction = b.text(r.get(13)) or ""
        for area, pts in spawns.items():
            ui = amap.get(area)
            if ui is None:
                ui = amap.get(sub.get(area, -1))
            if not ui:
                continue
            for p in (pts or [])[:3]:
                if p[0] is None or p[0] < 0:
                    continue
                out.setdefault(ui, set()).add((label, kind, round(p[0] / 100, 3), round(p[1] / 100, 3), name, faction))
                n += 1
    lines = ["-- SeviathsUsefulTools - profession trainers, bankers and auctioneers of each zone (UiMapId): { label, kind, x, y, npc name, faction }.",
             "-- Generated by tools/bake_services.py from the data of Questie / QuestieDB (GPL-3.0).", "local _, SFP = ...", "SFP.ServicePins = {"]
    for ui in sorted(out):
        lines.append("[%d]={" % ui)
        for label, kind, x, y, name, faction in sorted(out[ui]):
            lines.append("{%s,%s,%s,%s,%s%s}," % (b.lua_str(label), b.lua_str(kind), x, y, b.lua_str(name), (",%s" % b.lua_str(faction)) if faction else ""))
        lines.append("},")
    lines += ["}", ""]
    open(os.path.join(b.ADDON, "Data", "ServicePins.lua"), "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("pins:", n, "zones:", len(out))


if __name__ == "__main__":
    main()
