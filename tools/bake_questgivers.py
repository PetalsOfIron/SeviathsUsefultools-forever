"""Bakes Data/QuestGivers.lua from tools/crawl/questgivers.txt (made by crawl_questgivers.py). Run: python tools/bake_questgivers.py"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.dirname(HERE)
# Wowhead zone number -> uiMapID of WoW Forever (Classic Era numbers)
MAPS = {12: 1429, 1: 1426, 14: 1411, 215: 1412, 141: 1438, 85: 1420, 40: 1436, 38: 1432, 148: 1439, 17: 1413, 130: 1421, 44: 1433, 10: 1431, 11: 1437,
        267: 1424, 331: 1440, 406: 1442, 400: 1441, 36: 1416, 45: 1417, 33: 1434, 405: 1443, 3: 1418, 8: 1435, 15: 1445, 357: 1444, 440: 1446, 47: 1425,
        51: 1427, 46: 1428, 4: 1419, 490: 1449, 16: 1447, 361: 1448, 493: 1450, 1377: 1451, 618: 1452, 139: 1423, 28: 1422, 41: 1430,
        1519: 1453, 1537: 1455, 1657: 1457, 1637: 1454, 1638: 1456, 1497: 1458}
by = {}
n = 0
for line in open(os.path.join(HERE, "crawl", "questgivers.txt"), encoding="utf8").read().splitlines():
    p = line.split("|", 3)
    if len(p) < 4 or not p[2]:
        continue
    # holiday and event quests (the Darkmoon Faire, seasonal events) are level 60 quests that need only a few levels: they are not part of the zones
    keep = []
    for q in p[3].split(","):
        f = q.split(":")
        if len(f) >= 5 and f[1].isdigit() and f[2].isdigit() and int(f[1]) >= 60 and int(f[2]) <= 30:
            continue
        keep.append(q)
    if not keep:
        continue
    p[3] = ",".join(keep)
    qs = p[3].replace('"', "'")
    for part in p[2].split("~"):
        area, pts = part.split(":", 1)
        m = MAPS.get(int(area))
        if not m:
            continue
        x, y = pts.split(";")[0].split(",")
        by.setdefault(m, []).append('{"%s",%s,%s,"%s"}' % (p[1].replace('"', "'"), x, y, qs.replace(",", "|")))
        n += 1
# the quest givers the retail addon recorded in Classic zones (only Classic quest numbers; tools/crawl/retail_questgivers.json), when the crawl has not got them
import json
rp = os.path.join(HERE, "crawl", "retail_questgivers.json")
if os.path.exists(rp):
    seen = set()
    for m, lst in by.items():
        for e in lst:
            seen.add((m, e.split(",")[0].lower()))
    for r in json.load(open(rp, encoding="utf8")):
        if r["q"] > 9500:
            continue
        nm = r["n"].replace(chr(92), "").replace('"', "'")
        if (r["m"], ('{"%s"' % nm).lower()) in seen:
            continue
        by.setdefault(r["m"], []).append('{"%s",%.1f,%.1f,"%d:%d:0:0:%s"}' % (nm, r["x"], r["y"], r["q"], r["l"], r["t"].replace("|", "/").replace('"', "'").replace(chr(92), "")))
        n += 1
out = ["-- SeviathsUsefulTools - the quest givers of Classic: { name, x, y, 'questID:level:required level:side:name|...' } by map (generated by tools/bake_questgivers.py)",
       "local _, SFP = ...", "SFP.QuestGivers = {"]
for m in sorted(by):
    out.append("[%d] = {\n%s,\n}," % (m, ",\n".join(by[m])))
out.append("}\n")
open(os.path.join(ADDON, "Data", "QuestGivers.lua"), "w", encoding="utf8", newline="\n").write("\n".join(out))
print(n, "quest givers on", len(by), "maps")
